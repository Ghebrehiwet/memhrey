class AlphabetSet {
  final int index;
  final List<AlphabetLetter> letters;
  final String matchWord;
  final String matchImage;
  final String matchAudio;
  final String matchEmoji;

  const AlphabetSet({
    required this.index,
    required this.letters,
    required this.matchWord,
    required this.matchImage,
    required this.matchAudio,
    this.matchEmoji = '',
  });
}

class AlphabetLetter {
